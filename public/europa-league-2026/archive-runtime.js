const activeSeasonArchive=window.uelSeasonArchives?.[window.uelSeason?.key];
if(!activeSeasonArchive)throw new Error(`Missing Europa League archive for ${window.uelSeason?.key||'unknown season'}`);
const uelNames=activeSeasonArchive.names;
const aliases={...activeSeasonArchive.aliases};
Object.entries(activeSeasonArchive.aliases||{}).forEach(([raw,name])=>{aliases[raw]=name});
const leagueTeams=activeSeasonArchive.catalog.map(team=>[team.name,team.code]);
const rawMatches=activeSeasonArchive.matches.map(row=>row.slice());
const rawUpcoming=activeSeasonArchive.leagueFixtures.map(fixture=>({...fixture}));
window.uelLeagueCatalog=activeSeasonArchive.catalog.map(team=>({...team}));
window.uelLeagueFixtures=activeSeasonArchive.leagueFixtures.map(fixture=>({...fixture}));
window.uelLeagueDraw=Object.fromEntries(Object.entries(activeSeasonArchive.draw).map(([name,rows])=>[name,rows.map(row=>({...row}))]));
window.uelOfficialStandings=activeSeasonArchive.finalStandings.map(row=>({...row}));
window.uelCanonical=value=>aliases[String(value||'').trim()]||String(value||'').trim();
window.uelTeamInfo=value=>window.uelLeagueCatalog.find(team=>team.name===window.uelCanonical(value));
window.uelEntryLabels={direct:'直接晋级 / 转入',uel:'资格赛晋级',ucl:'欧冠转入'};
const uelQualifyingNames=uelNames;
const uelQualifyingTies=activeSeasonArchive.qualifyingTies.map(tie=>({...tie}));
const uelPlayoffTies=activeSeasonArchive.playoffTies.map(tie=>({...tie}));
const uelThirdRoundOrigins={};
window.uelArchive=activeSeasonArchive;
